import assert from 'node:assert/strict';
import { runInNewContext } from 'node:vm';

const base = process.argv[2];
assert.match(base, /^http:\/\/127\.0\.0\.1:[0-9]+$/);
const page = await fetch(base + '/');
assert.equal(page.status, 200);
assert.match(await page.text(), /src="\/runtime-config\.js"/);
const runtime = await fetch(base + '/runtime-config.js');
assert.equal(runtime.status, 200);
assert.equal(runtime.headers.get('cache-control'), 'no-store');
const script = await runtime.text();
assert.ok(!script.includes('</script>'), 'Public script must safely escape script-sensitive text');
const sandbox = {};
runInNewContext(script, sandbox, { timeout: 1000 });
assert.equal(sandbox.__DAO_PUBLIC_CONFIG__.VITE_API_BASE_URL, '/backend');
assert.equal(sandbox.__DAO_PUBLIC_CONFIG__.VITE_DATA_SOURCE, 'live');
assert.equal(sandbox.__DAO_PUBLIC_CONFIG__.VITE_CHAIN_NAME, 'Smoke </script> " \\ \u2028');
assert.ok(!Object.keys(sandbox.__DAO_PUBLIC_CONFIG__).some(key => /SECRET|PASSWORD|PRIVATE/.test(key)));
const health = await fetch(base + '/backend/api/health?chainId=31337&deploymentId=container-smoke');
assert.equal(health.status, 200);
const body = await health.json();
assert.equal(body.data.database, 'up');
assert.equal(body.data.publication, 'ready');
assert.equal(body.context.chainId, '31337');
assert.equal(body.context.deploymentId, 'container-smoke');
const summary = await fetch(base + '/backend/api/summary?chainId=31337&deploymentId=container-smoke');
assert.equal(summary.status, 200);
assert.equal((await summary.json()).context.dataKind, 'chain');
console.log('Live runtime configuration, safe JS serialization, API proxy and chain publication: PASS');
