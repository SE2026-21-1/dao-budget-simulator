"""Export/check compiler-owned SC06 ABIs and their generated interface catalog.

Run forge build first. --write exports only TV1-owned shared files; Timelock's
shared ABI remains owned by SC05 until PR #33 merges. No chain access or receipts.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACTS = ("GovernanceToken", "BudgetToken", "Treasury", "BudgetGovernor", "ITreasury", "TimelockController")
CATALOG = Path("docs/sc06-abi-reference.md")


def abi_type(item):
    kind = item["type"]
    if kind.startswith("tuple"):
        return "(" + ",".join(abi_type(c) for c in item["components"]) + ")" + kind[5:]
    return kind


def signature(item):
    return item["name"] + "(" + ",".join(abi_type(i) for i in item["inputs"]) + ")"


def canonical(abi):
    # ABI array order is irrelevant; argument order, indexed flags, outputs and
    # mutability remain significant. Overloads are never collapsed by name.
    return sorted(json.dumps(i, sort_keys=True, ensure_ascii=False) for i in abi)


def catalog(abis):
    lines = ["# SC06 — Compiler ABI reference", "",
             "Generated by `python3 scripts/check_sc06_abi.py --write` after `forge build`.",
             "Do not edit this catalog by hand. Includes inherited functions/errors/events;",
             "ABI presence does not grant permission to call a restricted function.",
             "Timelock is read from the pinned compiler artifact; its shared file is deferred to SC05 PR #33.", ""]
    for name, abi in abis.items():
        lines += ["## " + name, "", "### Public/external functions", "",
                  "| Signature | Mutability | Outputs |", "|---|---|---|"]
        for item in sorted((i for i in abi if i["type"] == "function"), key=signature):
            outputs = ", ".join(abi_type(i) + " " + i.get("name", "") for i in item["outputs"])
            lines.append(f"| `{signature(item)}` | {item['stateMutability']} | `{outputs or 'none'}` |")
        lines += ["", "### Events", "", "| Signature | Parameters (indexed explicitly marked) | Anonymous |", "|---|---|---|"]
        for item in sorted((i for i in abi if i["type"] == "event"), key=signature):
            params = ", ".join(abi_type(i) + (" indexed " if i.get("indexed") else " ") + i.get("name", "") for i in item["inputs"])
            lines.append(f"| `{signature(item)}` | `{params}` | {str(item.get('anonymous', False)).lower()} |")
        lines += ["", "### Custom errors", ""]
        errors = sorted((i for i in abi if i["type"] == "error"), key=signature)
        lines += ["- `" + signature(i) + "`" for i in errors] or ["No custom errors in this ABI."]
        lines.append("")
    return "\n".join(lines) + "\n"


def run(root=ROOT, write=False):
    abis = {}
    for name in CONTRACTS:
        artifact = root / "out" / (name + ".sol") / (name + ".json")
        abis[name] = json.loads(artifact.read_text())["abi"]
        shared = root / "shared/abi" / (name + ".json")
        if write and name != "TimelockController":
            shared.write_text(json.dumps(abis[name], ensure_ascii=False, indent=2) + "\n")
        if name == "TimelockController" and not shared.exists():
            print("DEFERRED: shared TimelockController ABI belongs to SC05 PR #33; artifact catalog checked")
            continue
        if canonical(json.loads(shared.read_text())) != canonical(abis[name]):
            raise ValueError(f"{shared.relative_to(root)} differs from compiler ABI; rebuild/export and review")
    expected = catalog(abis)
    path = root / CATALOG
    if write:
        path.write_text(expected)
    if path.read_text() != expected:
        raise ValueError(f"{CATALOG} is stale; regenerate and review")
    print("SC06 ABI/catalog compatibility passed (6 compiler artifacts)")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Export shared ABIs and generated catalog")
    args = parser.parse_args()
    run(write=args.write)
